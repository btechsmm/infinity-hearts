// Generates supabase/seed.sql from src/data/quotes.json so the app bundle and database never drift.
import { readFileSync, writeFileSync } from 'node:fs';

const quotes = JSON.parse(readFileSync(new URL('../src/data/quotes.json', import.meta.url), 'utf8'));
const esc = (s) => s.replace(/'/g, "''");
const rows = quotes.map((q) => `  (null, '${q.c}', '${q.f}', '${q.a}', '${esc(q.m)}')`).join(',\n');
const sql = `-- GENERATED by scripts/gen-seed.mjs from src/data/quotes.json. Do not edit by hand.
-- Shared quote library (couple_id is null). Safe to re-run.
insert into public.quotes (couple_id, category, frequency, audience, message) values
${rows}
on conflict do nothing;
`;
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`seed.sql written with ${quotes.length} quotes`);
